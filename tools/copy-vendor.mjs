// Copies the third-party libraries from node_modules (installed by `npm install`) into app/vendor/,
// together with their licence files, and writes app/vendor/THIRD_PARTY_NOTICES.md.
// Run with: npm run vendor   (npm run build also runs it)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..'); // works with Windows paths and spaces
const nm = path.join(root, 'node_modules');
const out = path.join(root, 'app', 'vendor');

// [package, files/folders to copy (relative to the package), destination folder in app/vendor, licence]
const LIBS = [
  ['pdfjs-dist', ['build/pdf.min.js', 'build/pdf.worker.min.js', 'web/pdf_viewer.css', 'cmaps', 'standard_fonts'], 'pdfjs', 'Apache-2.0'],
  ['docx', ['build/index.umd.js'], 'docx', 'MIT'],
  ['@phosphor-icons/web', ['src/regular/style.css', 'src/regular/Phosphor.woff2'], 'phosphor', 'MIT'],
  ['tailwindcss', [], 'tailwind', 'MIT'] // tailwind.css itself is generated by `npm run css`
];
const LICENSE_NAMES = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'license', 'LICENCE'];

function fail(msg) { console.error('\n✖ ' + msg + '\n'); process.exit(1); }
if (!fs.existsSync(nm)) fail('node_modules not found. Run `npm install` first.');

const notices = [
  '# Third-party software bundled with Meta-Ethnography Canvas',
  '',
  'Generated by tools/copy-vendor.mjs. Each library keeps its own licence (copied next to it).',
  ''
];
for (const [pkg, items, dest, licence] of LIBS) {
  const pkgDir = path.join(nm, pkg);
  if (!fs.existsSync(pkgDir)) fail(`${pkg} is not installed. Run \`npm install\`.`);
  const meta = JSON.parse(fs.readFileSync(path.join(pkgDir, 'package.json'), 'utf8'));
  const destDir = path.join(out, dest);
  // Keep a generated tailwind.css; refresh everything else
  for (const entry of fs.existsSync(destDir) ? fs.readdirSync(destDir) : []) {
    if (!(dest === 'tailwind' && entry === 'tailwind.css')) fs.rmSync(path.join(destDir, entry), { recursive: true, force: true });
  }
  fs.mkdirSync(destDir, { recursive: true });
  for (const item of items) {
    const from = path.join(pkgDir, item);
    if (!fs.existsSync(from)) fail(`${pkg}@${meta.version}: "${item}" not found. Check the path in tools/copy-vendor.mjs.`);
    fs.cpSync(from, path.join(destDir, path.basename(item)), { recursive: true });
  }
  const lic = LICENSE_NAMES.map(n => path.join(pkgDir, n)).find(p => fs.existsSync(p));
  if (!lic) fail(`${pkg}: no licence file found in the package.`);
  fs.copyFileSync(lic, path.join(destDir, 'LICENSE'));
  const notice = ['NOTICE', 'NOTICE.txt', 'NOTICE.md'].map(n => path.join(pkgDir, n)).find(p => fs.existsSync(p));
  if (notice) fs.copyFileSync(notice, path.join(destDir, 'NOTICE'));
  notices.push(`- **${pkg}** ${meta.version} — ${licence} — ${meta.homepage || (meta.repository && (meta.repository.url || meta.repository)) || ''}  `,
               `  files: app/vendor/${dest}/ · licence text: app/vendor/${dest}/LICENSE${notice ? ' · NOTICE: app/vendor/' + dest + '/NOTICE' : ''}`);
  console.log(`✔ ${pkg}@${meta.version} → app/vendor/${dest}/`);
}
// ---- Post-processing ----
// 1) Phosphor: only the woff2 font is shipped (every current browser supports it), so trim the @font-face list.
const phCss = path.join(out, 'phosphor', 'style.css');
let css = fs.readFileSync(phCss, 'utf8');
const trimmed = css.replace(/src:\s*url\("\.\/Phosphor\.woff2"\) format\("woff2"\)[^;]*;/, 'src: url("./Phosphor.woff2") format("woff2");');
if (trimmed === css) fail('phosphor/style.css: @font-face src not in the expected form; check tools/copy-vendor.mjs.');
fs.writeFileSync(phCss, '/* Modified by Meta-Ethnography Canvas: @font-face reduced to the woff2 file. */\n' + trimmed);
console.log('✔ phosphor/style.css trimmed to woff2');

// 2) PDF.js data as <script> files for the offline edition (file:// cannot fetch/XHR local files).
function writeDataScripts(srcDir, destDir, prefix, keep) {
  fs.mkdirSync(destDir, { recursive: true });
  let n = 0;
  for (const f of fs.readdirSync(srcDir)) {
    if (!keep(f)) continue;
    const key = prefix === 'cmap:' ? f.replace(/\.bcmap$/, '') : f;
    const b64 = fs.readFileSync(path.join(srcDir, f)).toString('base64');
    fs.writeFileSync(path.join(destDir, key + '.js'), `window.__mecPdfjsData(${JSON.stringify(prefix + key)},"${b64}");\n`);
    n++;
  }
  return n;
}
const pdfjsOut = path.join(out, 'pdfjs');
const nC = writeDataScripts(path.join(pdfjsOut, 'cmaps'), path.join(pdfjsOut, 'offline', 'cmaps'), 'cmap:', f => f.endsWith('.bcmap'));
const nF = writeDataScripts(path.join(pdfjsOut, 'standard_fonts'), path.join(pdfjsOut, 'offline', 'standard_fonts'), 'font:', f => /\.(pfb|ttf)$/i.test(f));
console.log(`✔ pdfjs/offline: ${nC} CMaps, ${nF} standard fonts as <script> files`);
notices.push('', 'PDF.js data files keep their own licences: CMaps → app/vendor/pdfjs/cmaps/LICENSE; standard fonts → app/vendor/pdfjs/standard_fonts/LICENSE_FOXIT and LICENSE_LIBERATION. app/vendor/pdfjs/offline/ holds the same data re-encoded as <script> files for the offline edition.');
notices.push('', 'The docx bundle also contains its own dependencies (e.g. JSZip, used under its MIT option); their notices are kept inside build/index.umd.js.', '');
fs.writeFileSync(path.join(out, 'THIRD_PARTY_NOTICES.md'), notices.join('\n'));
console.log('✔ app/vendor/THIRD_PARTY_NOTICES.md');
